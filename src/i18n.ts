export type TranslationKey = keyof typeof messages["pt-BR"];

let currentLanguage: AppLanguage = "pt-BR";

export function getLanguage(): AppLanguage {
  return currentLanguage;
}

export function setLanguage(language: AppLanguage): void {
  currentLanguage = language;
  document.documentElement.lang = language;
}

export function t(key: TranslationKey, values: Record<string, string | number> = {}): string {
  let value: string = messages[currentLanguage][key];
  for (const [name, replacement] of Object.entries(values)) {
    value = value.split(`{${name}}`).join(String(replacement));
  }
  return value;
}

export function translateDocument(root: ParentNode = document): void {
  root.querySelectorAll<HTMLElement>("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n as TranslationKey;
    element.textContent = t(key);
  });
  root.querySelectorAll<HTMLInputElement>("[data-i18n-placeholder]").forEach((element) => {
    element.placeholder = t(element.dataset.i18nPlaceholder as TranslationKey);
  });
  root.querySelectorAll<HTMLElement>("[data-i18n-title]").forEach((element) => {
    const value = t(element.dataset.i18nTitle as TranslationKey);
    element.title = value;
    element.setAttribute("aria-label", value);
  });
}
